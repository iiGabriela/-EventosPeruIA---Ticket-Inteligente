CREATE FUNCTION public.fn_ventas_por_evento(p_organizador_id integer, p_desde timestamp with time zone DEFAULT NULL::timestamp with time zone, p_hasta timestamp with time zone DEFAULT NULL::timestamp with time zone) RETURNS TABLE(evento_id integer, nombre character varying, fecha_inicio timestamp with time zone, fecha_fin timestamp with time zone, sede character varying, precio numeric, aforo_total integer, estado character varying, entradas_vendidas_total integer, entradas_vendidas integer, recaudado numeric)
    LANGUAGE sql STABLE
    AS $$
    SELECT e.evento_id,
           e.nombre::varchar,
           e.fecha_inicio,
           e.fecha_fin,
           e.sede::varchar,
           e.precio::numeric,
           e.aforo_total,
           e.estado::varchar,
           COALESCE(SUM(c.cantidad), 0)::integer,
           COALESCE(SUM(c.cantidad) FILTER (
               WHERE (p_desde IS NULL OR c.fecha_compra >= p_desde)
                 AND (p_hasta IS NULL OR c.fecha_compra < p_hasta)), 0)::integer,
           COALESCE(SUM(c.cantidad * c.precio_unitario) FILTER (
               WHERE (p_desde IS NULL OR c.fecha_compra >= p_desde)
                 AND (p_hasta IS NULL OR c.fecha_compra < p_hasta)), 0)::numeric
    FROM evento e
    LEFT JOIN compra c ON c.evento_id = e.evento_id AND c.estado = 'CONFIRMADA'
    WHERE e.organizador_id = p_organizador_id
    GROUP BY e.evento_id
    ORDER BY e.fecha_inicio DESC;
$$;


